/* Stage73: start at MAP02's authentic spawn; follow controller-style
 * LEFT/RIGHT/RUN/JUMP bitmasks through the original fixed 60 Hz engine.
 * No direct position changes, fixture pickups, or checkpoint teleports.
 * Host-side button replay, NOT proof of Switch HID or SD durability.
 */
#include "rikitu_mill.h"
#include "rikitu_demo.h"
#include "rikitu_level_save.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>

#define A "/tmp/rikitu-stage73-controller-a.rkl"
#define B "/tmp/rikitu-stage73-controller-b.rkl"
#define RIGHT_RUN (RIKITU_INPUT_RIGHT|RIKITU_INPUT_RUN)

static void fresh(RikituScene *scene,RikituLoop *loop){
  rikitu_mill_init(scene);
  memset(loop,0,sizeof(*loop));
  loop->player=scene->player;
}
static void tick(RikituScene *scene,RikituLoop *loop,unsigned buttons){
  if(rikitu_demo_advance(scene,loop,RIKITU_FIXED_DT,buttons)!=1){
    fprintf(stderr,"Stage73 engine failed at x=%.2f y=%.2f\n",
            (double)loop->player.x,(double)loop->player.y);
    assert(0 && "60Hz game tick");
  }
}
int main(void){
  RikituScene scene,loaded;
  RikituLoop loop,reboot;
  RikituCampaign campaign;
  uint8_t buf[RIKITU_LEVEL_SAVE_BYTES];
  uint32_t generation;
  int frames=0,jump_coin=0,jump_fragment=0,jump_gap=0;
  int coins,fragments,damage_before,hearts_before,damage_after,hearts_after;
  float checkpoint_x;
  FILE *f;
  (void)remove(A);(void)remove(B);
  assert(rikitu_campaign_init(&campaign,2));
  campaign.wallet=21;
  fresh(&scene,&loop);
  assert(loop.player.x==105.0f && scene.reached_checkpoints==0);

  /* Travel from original spawn to MAP02 checkpoint 1. Every X increase
   * is generated by RIGHT+RUN. Three edge-triggered jumps are needed
   * for the opening coin, raised fragment and first real floor gap. */
  while(scene.reached_checkpoints==0 && frames<1800){
    unsigned input=RIGHT_RUN;
    if(!jump_coin && loop.player.grounded && loop.player.x>109.0f){
      input|=RIKITU_INPUT_JUMP;jump_coin=1;
    }else if(!jump_fragment && jump_coin && loop.player.grounded &&
             loop.player.x>1450.0f && loop.player.x<1530.0f){
      input|=RIKITU_INPUT_JUMP;jump_fragment=1;
    }else if(!jump_gap && jump_fragment && loop.player.grounded &&
             loop.player.x>1715.0f && loop.player.x<1805.0f){
      input|=RIKITU_INPUT_JUMP;jump_gap=1;
    }
    tick(&scene,&loop,input);
    frames++;
  }
  if(scene.reached_checkpoints!=1 || !jump_coin ||
     !jump_fragment || !jump_gap ||
     !scene.stage.coins[0] || !scene.stage.fragments[0]){
    fprintf(stderr,"Stage73 route failure: ticks=%d x=%.2f y=%.2f "
            "checkpoint=%d jumps=%d%d%d coin=%u fragment=%u hearts=%d\n",
            frames,(double)loop.player.x,(double)loop.player.y,
            scene.reached_checkpoints,jump_coin,jump_fragment,jump_gap,
            (unsigned)scene.stage.coins[0],(unsigned)scene.stage.fragments[0],
            scene.hearts);
    return 1;
  }
  assert(loop.player.x>=scene.checkpoints[0]);
  assert(scene.active_checkpoint==scene.checkpoints[0]);
  assert(frames>400 && loop.active_seconds>5.0f);
  checkpoint_x=scene.active_checkpoint;
  assert(rikitu_level_save_store_pair(A,B,&scene,&loop,&campaign));
  f=fopen(A,"rb");assert(f);
  assert(fread(buf,1,sizeof(buf),f)==sizeof(buf));
  assert(fclose(f)==0);
  generation=0;
  assert(rikitu_level_save_inspect(buf,sizeof(buf),&generation));
  assert(generation==1);

  /* Keep moving with button input past checkpoint to the second gap.
   * Stop over the actual missing floor and fall under gravity.
   * The native gameplay code—not this test—must activate respawn. */
  for(frames=0;loop.player.x<3253.0f && frames<1500;frames++){
    tick(&scene,&loop,RIGHT_RUN);
    assert(scene.reached_checkpoints==1);
  }
  if(loop.player.x<3253.0f || loop.player.x>=3297.0f){
    fprintf(stderr,"Stage73 could not reach pit: x=%.2f frames=%d\n",
            (double)loop.player.x,frames);
    return 2;
  }
  assert(scene.active_checkpoint==checkpoint_x);
  damage_before=scene.damage_count;
  hearts_before=scene.hearts;
  for(frames=0;scene.damage_count==damage_before && frames<130;frames++){
    tick(&scene,&loop,0);
  }
  if(scene.damage_count!=damage_before+1){
    fprintf(stderr,"Stage73 pit respawn missing: frames=%d x=%.2f y=%.2f "
            "damage=%d before=%d\n",frames,(double)loop.player.x,
            (double)loop.player.y,scene.damage_count,damage_before);
    return 3;
  }
  assert(loop.player.x==checkpoint_x);
  assert(scene.reached_checkpoints==1);
  assert(scene.invulnerability_seconds>0.0f);
  assert(scene.hearts==(hearts_before==1?scene.max_hearts:hearts_before-1));
  assert(scene.stage.coins[0] && scene.stage.fragments[0]);
  assert(!scene.stage.completed);
  coins=scene.stage.coin_count;
  fragments=scene.stage.fragment_count;
  damage_after=scene.damage_count;
  hearts_after=scene.hearts;
  assert(rikitu_level_save_store_pair(A,B,&scene,&loop,&campaign));
  f=fopen(B,"rb");assert(f);
  assert(fread(buf,1,sizeof(buf),f)==sizeof(buf));
  assert(fclose(f)==0);
  generation=0;
  assert(rikitu_level_save_inspect(buf,sizeof(buf),&generation));
  assert(generation==2);

  /* Cold scene initialization; checkpoint restart is loaded from RKL3. */
  fresh(&loaded,&reboot);
  assert(rikitu_level_save_load_pair(A,B,&loaded,&reboot,&campaign));
  assert(loaded.reached_checkpoints==1 &&
         loaded.active_checkpoint==checkpoint_x);
  assert(reboot.player.x==checkpoint_x &&
         loaded.player.x==checkpoint_x);
  assert(loaded.stage.coins[0] && loaded.stage.fragments[0]);
  assert(loaded.stage.coin_count==coins &&
         loaded.stage.fragment_count==fragments);
  assert(loaded.hearts==hearts_after &&
         loaded.damage_count==damage_after);
  assert(loaded.invulnerability_seconds>0.0f);

  /* Pause and resume controller input without changing the loaded state. */
  reboot.paused=1;
  for(frames=0;frames<30;frames++){
    assert(rikitu_demo_advance(&loaded,&reboot,RIKITU_FIXED_DT,
                               RIGHT_RUN)==0);
  }
  assert(reboot.player.x==checkpoint_x && loaded.stage.coin_count==coins);
  reboot.paused=0;
  for(frames=0;frames<30;frames++)tick(&loaded,&reboot,RIGHT_RUN);
  assert(reboot.player.x>checkpoint_x+100.0f);
  assert(loaded.reached_checkpoints==1);
  assert(loaded.stage.coin_count==coins &&
         loaded.stage.fragment_count==fragments);
  assert(loaded.damage_count==damage_after);
  (void)remove(A);(void)remove(B);
  puts("PASS MAP02: real button route -> checkpoint -> pit respawn -> "
       "two RKL3 generations -> reboot -> pause/resume movement");
  return 0;
}
